const schema = 'https://tau.new/schemas/tau-v1.json';
const legacySchema = 'https://tau.new/schemas/tau-schema-v1.json';
const modifier = process.platform === 'darwin' ? 'Meta' : 'Control';
const account = tauTestAccount('identity-acceptance');
let token = '';
let owner: TauCloudOwnerIds | undefined;
let server: UiServer | undefined;

/** A valid historical ID generated by the fixture rather than hand-invented. */
const fixtureId = (): string => `proj_${randomBytes(16).toString('hex').slice(0, 21)}`;

/** Authored declarations contain identity only when explicitly representing the old release. */
const declaration = (name: string, legacyId?: string): string =>
  JSON.stringify({
    $schema: legacyId ? legacySchema : schema,
    ...(legacyId ? { id: legacyId } : {}),
    name,
    description: 'Identity acceptance',
    tags: [],
    assets: { main: { entryPath: 'main.scad' } },
  });

/** Read actual OPFS bytes, independently of the application's in-memory identity. */
const browserFile = async (page: BrowserClient['page'], slug: string, path: string): Promise<string> =>
  page.evaluate(
    async ({ slug, path }) => {
      let directory = await navigator.storage.getDirectory();
      const parts = [slug, ...path.split('/')];
      for (const segment of parts.slice(0, -1)) {
        directory = await directory.getDirectoryHandle(segment);
      }
      const handle = await directory.getFileHandle(parts.at(-1)!);
      const file = await handle.getFile();
      return file.text();
    },
    { slug, path },
  );

/** Fail at the original Git command, retaining its error without its authorization arguments. */
const git = async (root: string, args: readonly string[]): Promise<string> => {
  const result = await runGit(args, root);
  expect(result.code, result.stderr).toBe(0);
  return result.stdout.trim();
};

beforeAll(async () => {
  token = await seedTauTestUser(account);
  owner = await tauCloudOwnerIds(account.email);
  await seedProPlan(owner);
  server = await startUiServer();
});

afterAll(async () => {
  await server?.close();
  if (owner) {
    await forgetSeededProjects(owner);
  }
  if (token) {
    await deleteTauTestUser(account.email);
  }
});

it.each([false, true])('should admit browser-authored bytes without manual metadata (legacy=%s)', async (legacy) => {
  const browser = await launchBrowserClient({ oneTimeToken: await mintOneTimeToken(token) });
  const name = legacy ? 'Legacy browser identity' : 'Authored browser identity';
  const slug = legacy ? 'legacy-browser-identity' : 'authored-browser-identity';
  const expectedId = legacy ? fixtureId() : undefined;
  try {
    await browser.page.goto('/');
    await browser.page.evaluate(
      async ({ slug, manifest }) => {
        const root = await navigator.storage.getDirectory();
        const directory = await root.getDirectoryHandle(slug, { create: true });
        for (const [path, content] of [
          ['tau.json', manifest],
          ['main.scad', 'cube(4);\n'],
        ] as const) {
          const file = await directory.getFileHandle(path, { create: true });
          const writer = await file.createWritable();
          await writer.write(content);
          await writer.close();
        }
      },
      { slug, manifest: declaration(name, expectedId) },
    );
    await browser.page.goto('/projects');
    await browser.page.getByRole('link', { name: `Open ${name}`, exact: true }).click();
    await browser.page.waitForURL(/\/w\//u);
    const identity = JSON.parse(await browserFile(browser.page, slug, '.tau/project.json')) as {
      version: number;
      projectId: string;
    };
    expect(identity.version).toBe(1);
    expect(identity.projectId).toMatch(/^proj_[\dA-Za-z]{21}$/u);
    if (expectedId) {
      expect(identity.projectId).toBe(expectedId);
    }
    expect(JSON.parse(await browserFile(browser.page, slug, 'tau.json'))).toMatchObject({ $schema: schema, name });
    expect(JSON.parse(await browserFile(browser.page, slug, 'tau.json'))).not.toHaveProperty('id');
    expect(await browserFile(browser.page, slug, 'main.scad')).toBe('cube(4);\n');
    await browser.page.reload();
    expect(JSON.parse(await browserFile(browser.page, slug, '.tau/project.json'))).toEqual(identity);
    await browser.page.goto('/projects');
    await browser.page.getByRole('button', { name: `Actions for ${name}`, exact: true }).click();
    await browser.page.getByRole('menuitem', { name: 'Duplicate', exact: true }).click();
    const duplicateSlug = `${slug}-copy`;
    await expect
      .poll(async () => JSON.parse(await browserFile(browser.page, duplicateSlug, '.tau/project.json')) as unknown, {
        timeout: 60_000,
      })
      .toMatchObject({ version: 1 });
    const duplicateIdentity = JSON.parse(await browserFile(browser.page, duplicateSlug, '.tau/project.json')) as {
      projectId: string;
    };
    expect(duplicateIdentity.projectId).toMatch(/^proj_[\dA-Za-z]{21}$/u);
    expect(duplicateIdentity.projectId).not.toBe(identity.projectId);
    await expect
      .poll(async () => browserFile(browser.page, duplicateSlug, 'main.scad'), { timeout: 60_000 })
      .toBe('cube(4);\n');
  } catch (error) {
    await browser.capture(`identity-browser-${String(legacy)}`);
    throw error;
  } finally {
    await browser.close();
  }
});

it('should preserve a legacy cloud identity through browser and CLI sync without rewriting history', async () => {
  const root = await mkdtemp(join(tmpdir(), 'tau-identity-cloud-'));
  const seed = join(root, 'seed');
  const clone = join(root, 'clone');
  const projectId = fixtureId();
  const name = 'Legacy cloud identity';
  const legacyBytes = declaration(name, projectId);
  const browser = await launchBrowserClient({ oneTimeToken: await mintOneTimeToken(token) });
  try {
    await mkdir(seed);
    await git(seed, ['init', '--quiet', '--initial-branch=main']);
    await git(seed, ['config', 'user.name', 'Identity acceptance']);
    await git(seed, ['config', 'user.email', 'identity@tau.invalid']);
    await writeFile(join(seed, 'tau.json'), legacyBytes);
    await writeFile(join(seed, 'main.scad'), 'cube(7);\n');
    await git(seed, ['add', 'tau.json', 'main.scad']);
    await git(seed, ['commit', '--quiet', '-m', 'Legacy project']);
    const historicalHead = await git(seed, ['rev-parse', 'HEAD']);
    if (!owner) {
      throw new Error('Identity acceptance account was not seeded');
    }
    await registerProjectOnRemote(owner, projectId, name);
    await git(seed, [
      '-c',
      `http.extraHeader=Authorization: ${basicAuthorization(token)}`,
      'push',
      `${desktopE2EApiUrl}/v1/git/${projectId}.git`,
      'HEAD:refs/heads/main',
    ]);
    const slug = await openCloudOnlyProject(browser.page, {
      projectsUrl: '/projects',
      name,
      message: 'Existing legacy cloud project',
    });
    await expect
      .poll(async () => browserFile(browser.page, slug, 'main.scad'), { timeout: 120_000 })
      .toBe('cube(7);\n');
    await browser.page
      .getByRole('button', { name: /^Open Revisions\./u })
      .first()
      .click();
    await expect
      .poll(async () => browser.page.getByRole('region', { name: 'Sync', exact: true }).first().textContent(), {
        timeout: 120_000,
      })
      .toContain('Backed up');
    // Admission converts the working declaration; that edit need not already be saved.
    expect(await revisionStatus(browser.page).textContent()).not.toContain('Needs your decision');
    expect(
      await browser.page.getByRole('region', { name: 'Couldn’t download this project', exact: true }).count(),
    ).toBe(0);
    expect(JSON.parse(await browserFile(browser.page, slug, '.tau/project.json'))).toEqual({ version: 1, projectId });
    expect(JSON.parse(await browserFile(browser.page, slug, 'tau.json'))).not.toHaveProperty('id');

    const opened = await runCli(['clone', projectId, '--into', clone, '--json'], token);
    expect(opened.code, opened.stderr).toBe(0);
    expect(cliRecord(opened)).toMatchObject({ ok: true, id: projectId });
    expect(JSON.parse(await readFile(join(clone, '.tau/project.json'), 'utf8'))).toEqual({ version: 1, projectId });
    expect(await git(clone, ['show', `${historicalHead}:tau.json`])).toBe(legacyBytes);
    await writeFile(join(clone, 'terminal.scad'), 'sphere(3);\n');
    const saved = await runCli(['revisions', 'save', '--project', clone, '--json'], token);
    expect(saved.code, saved.stderr).toBe(0);
    expect(cliRecord(saved)).toMatchObject({ ok: true, backup: 'backedUp' });
    await expect
      .poll(async () => browserFile(browser.page, slug, 'terminal.scad'), { timeout: 120_000 })
      .toBe('sphere(3);\n');
    await uploadFileInPage(browser.page, 'browser.scad', new TextEncoder().encode('cylinder(h=2,r=1);\n'));
    const beforeSave = await browserFile(browser.page, slug, '.git/refs/heads/main');
    await browser.page.keyboard.press(`${modifier}+KeyS`);
    await expect
      .poll(async () => browserFile(browser.page, slug, '.git/refs/heads/main'), { timeout: 120_000 })
      .not.toBe(beforeSave);
    await browser.page
      .getByRole('button', { name: /^Open Revisions\./u })
      .first()
      .click();
    await expect
      .poll(async () => revisionStatus(browser.page).textContent(), { timeout: 120_000 })
      .toBe('Saved · Backed up');
    const peer = join(root, 'peer');
    const returned = await runCli(['clone', projectId, '--into', peer, '--json'], token);
    expect(returned.code, `${returned.stdout}\n${returned.stderr}`).toBe(0);
    expect(await readFile(join(peer, 'browser.scad'), 'utf8')).toBe('cylinder(h=2,r=1);\n');
    expect(JSON.parse(await readFile(join(peer, '.tau/project.json'), 'utf8'))).toEqual({ version: 1, projectId });
    expect(await git(peer, ['show', `${historicalHead}:tau.json`])).toBe(legacyBytes);
    expect(await git(peer, ['ls-tree', '-r', '--name-only', 'HEAD'])).not.toContain('.tau/project.json');

    await restoreFromHistory(browser.page, browser.page.getByRole('button', { name: /^Rev 1 · /u }).first(), (n) =>
      historyRows(browser.page)
        .filter({ hasText: 'Current' })
        .filter({ hasText: `Restored Rev ${n}` }),
    );
    await expect
      .poll(async () => revisionStatus(browser.page).textContent(), { timeout: 120_000 })
      .toBe('Saved · Backed up');
    expect(JSON.parse(await browserFile(browser.page, slug, '.tau/project.json'))).toEqual({ version: 1, projectId });
    expect(JSON.parse(await browserFile(browser.page, slug, 'tau.json'))).not.toHaveProperty('id');
    const restored = join(root, 'restored');
    const restoredClone = await runCli(['clone', projectId, '--into', restored, '--json'], token);
    expect(restoredClone.code, `${restoredClone.stdout}\n${restoredClone.stderr}`).toBe(0);
    expect(await readFile(join(restored, 'main.scad'), 'utf8')).toBe('cube(7);\n');
    expect(JSON.parse(await readFile(join(restored, 'tau.json'), 'utf8'))).not.toHaveProperty('id');
    expect(JSON.parse(await readFile(join(restored, '.tau/project.json'), 'utf8'))).toEqual({ version: 1, projectId });
    await expect(readFile(join(restored, 'browser.scad'), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' });
    await expect(readFile(join(restored, 'terminal.scad'), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' });
    expect(await git(restored, ['show', `${historicalHead}:tau.json`])).toBe(legacyBytes);
  } catch (error) {
    await browser.capture('identity-cloud');
    throw error;
  } finally {
    await browser.close();
    await rm(root, { recursive: true, force: true });
  }
});
