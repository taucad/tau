import { listDocumentPaths } from '#lib/static-paths.js';
import { getRawMarkdownBackingPath } from '#lib/site.js';

/**
 * Emits Netlify's `_redirects` file into the static output.
 *
 * The `<page>.mdx` convention cannot be expressed as a Netlify pattern: splats
 * match only a trailing segment, so `/*.mdx` never fires, and placeholders do
 * not match part of a segment. Enumerating one forced rewrite per page from the
 * same inventory that drives prerendering keeps the convention working for
 * crawlers and agents without a hand-maintained rule list.
 */
export async function loader(): Promise<Response> {
  const documentPaths = await listDocumentPaths();
  const rules = [
    '# Generated by app/routes/[_redirects]/route.ts — do not edit by hand.',
    '/docs.mdx /_llms/runtime.txt 200!',
    ...documentPaths.map((documentPath) => `${documentPath}.mdx ${getRawMarkdownBackingPath(documentPath)} 200!`),
  ].join('\n');

  return new Response(`${rules}\n`, {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  });
}
