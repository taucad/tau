/**
 * The tscircuit authoring surface: the JSX intrinsic elements a `main.tsx`
 * writes, their props, the named prop types those props reference, the
 * footprint-string functions and the few helpers authors import.
 *
 * The surface is not a module's exports. `@tscircuit/core` registers its
 * elements on a non-exported `TscircuitElements` interface that augments
 * `JSX.IntrinsicElements`, and half of `@tscircuit/props`' prop types are
 * `z.input<typeof xProps>` aliases whose declarations are Zod schemas. So this
 * front-end walks that interface with the checker instead of
 * `checker.getExportsOfModule`, names each element by its tag (`<resistor>`)
 * so it is greppable from JSX, prints a Zod-derived prop as the type the
 * checker resolves rather than its schema, and lists only the props an element
 * adds over the largest shared base (`CommonComponentProps` and friends), which
 * become entries of their own.
 *
 * The corpus is committed (`generated/tscircuit/tscircuit.corpus.json`) and
 * regenerated by `nx run api-extractor:extract-tscircuit`: the program spans
 * ~20 MB of declarations that pnpm links only into the plugin's own
 * `node_modules`, and a committed file regenerates bundles identically without
 * either.
 *
 * @module
 */

