import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openCascade from 'replicad-opencascadejs';
import { setOC } from 'replicad';
import sharp from 'sharp';
import { tauBrandColor } from '../tau-brand.js';
import { createTauLogo } from './main.js';

setOC(await openCascade());

const formatPath = (path: string): string =>
  path.replaceAll(/-?\d+(?:\.\d+)?/g, (value) =>
    String(Number(Number(value).toFixed(5))),
  );

const paths = createTauLogo()
  .toSVGPaths()
  .flat()
  .map((path) => formatPath(path));
const pathData = paths.join(' ');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><path fill="${tauBrandColor}" d="${pathData}"/></svg>\n`;
const component = `// Generated by libs/tau-examples/src/kernels/replicad/logo/generate-logo.ts. Do not edit.
export const tauLogoPathData =
  '${pathData}';

export function Tau(properties: React.SVGProps<SVGSVGElement>): React.JSX.Element {
  return (
    <svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 512 512' {...properties}>
      <path fill='currentColor' d={tauLogoPathData} />
    </svg>
  );
}
`;
const emailPathModule = `// Generated by libs/tau-examples/src/kernels/replicad/logo/generate-logo.ts. Do not edit.
export const tauEmailLogoPathData =
  '${pathData}';
export const tauEmailLogoColor = '${tauBrandColor}';
`;

const rasterize = async ({
  size,
  background,
}: {
  size: number;
  background?: string;
}): Promise<Buffer> => {
  const image = sharp(Buffer.from(svg)).resize({ width: size, height: size });
  return (background ? image.flatten({ background }) : image).png().toBuffer();
};

const createIco = (
  images: ReadonlyArray<{ size: number; data: Buffer }>,
): Buffer => {
  const directorySize = 6 + images.length * 16;
  const directory = Buffer.alloc(directorySize);
  directory.writeUInt16LE(1, 2);
  directory.writeUInt16LE(images.length, 4);

  let offset = directorySize;
  for (const [index, image] of images.entries()) {
    const entry = 6 + index * 16;
    directory.writeUInt8(image.size, entry);
    directory.writeUInt8(image.size, entry + 1);
    directory.writeUInt16LE(1, entry + 4);
    directory.writeUInt16LE(32, entry + 6);
    directory.writeUInt32LE(image.data.length, entry + 8);
    directory.writeUInt32LE(offset, entry + 12);
    offset += image.data.length;
  }

  return Buffer.concat([directory, ...images.map(({ data }) => data)]);
};

const [favicon96, appleTouchIcon, android192, android512] = await Promise.all([
  rasterize({ size: 96 }),
  rasterize({ size: 180, background: '#ffffff' }),
  rasterize({ size: 192, background: '#ffffff' }),
  rasterize({ size: 512, background: '#ffffff' }),
]);
const icoImages = await Promise.all(
  [16, 32, 48].map(async (size) => ({ size, data: await rasterize({ size }) })),
);
const faviconIco = createIco(icoImages);
const directory = dirname(fileURLToPath(import.meta.url));
const workspaceRoot = join(directory, '../../../../../..');
const outputs = [
  [join(directory, 'logo.svg'), svg],
  [join(directory, '../logo-keychain/assets/logo.svg'), svg],
  [join(workspaceRoot, 'apps/ui/public/favicon.svg'), svg],
  [join(workspaceRoot, 'apps/ui/public/favicon-96x96.png'), favicon96],
  [join(workspaceRoot, 'apps/ui/public/apple-touch-icon.png'), appleTouchIcon],
  [
    join(workspaceRoot, 'apps/ui/public/android-chrome-192x192.png'),
    android192,
  ],
  [
    join(workspaceRoot, 'apps/ui/public/android-chrome-512x512.png'),
    android512,
  ],
  [join(workspaceRoot, 'apps/ui/public/favicon.ico'), faviconIco],
  [join(workspaceRoot, 'apps/ui/app/components/icons/tau.tsx'), component],
  [
    join(
      workspaceRoot,
      'apps/api/app/email/templates/tau-logo-path.generated.ts',
    ),
    emailPathModule,
  ],
] as const;

if (process.argv.includes('--check')) {
  for (const [output, expected] of outputs) {
    const expectedBytes =
      typeof expected === 'string' ? Buffer.from(expected) : expected;
    if (!readFileSync(output).equals(expectedBytes)) {
      throw new Error(`Generated logo differs: ${output}`);
    }
  }
} else {
  for (const [output, contents] of outputs) {
    writeFileSync(output, contents);
  }
}
