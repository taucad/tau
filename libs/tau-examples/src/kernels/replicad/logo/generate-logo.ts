import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openCascade from 'replicad-opencascadejs';
import { setOC } from 'replicad';
import { createTauLogo } from '#kernels/replicad/logo/main.js';

setOC(await openCascade());

const formatPath = (path: string): string =>
  path.replaceAll(/-?\d+(?:\.\d+)?/g, (value) =>
    String(Number(Number(value).toFixed(5))),
  );

const paths = createTauLogo()
  .toSVGPaths()
  .flat()
  .map((path) => formatPath(path));
const pathData = paths.join(' ');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><path fill="#008f7b" d="${pathData}"/></svg>\n`;
const component = `// Generated by libs/tau-examples/src/kernels/replicad/logo/generate-logo.ts. Do not edit.
export const tauLogoPathData =
  '${pathData}';

export function Tau(properties: React.SVGProps<SVGSVGElement>): React.JSX.Element {
  return (
    <svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 512 512' {...properties}>
      <path fill='currentColor' d={tauLogoPathData} />
    </svg>
  );
}
`;
const emailPathModule = `// Generated by libs/tau-examples/src/kernels/replicad/logo/generate-logo.ts. Do not edit.
export const tauEmailLogoPathData =
  '${pathData}';
`;
const directory = dirname(fileURLToPath(import.meta.url));
const workspaceRoot = join(directory, '../../../../../..');
const outputs = [
  [join(directory, 'logo.svg'), svg],
  [join(directory, '../logo-keychain/assets/logo.svg'), svg],
  [join(workspaceRoot, 'apps/ui/public/favicon.svg'), svg],
  [join(workspaceRoot, 'apps/ui/app/components/icons/tau.tsx'), component],
  [
    join(
      workspaceRoot,
      'apps/api/app/email/templates/tau-logo-path.generated.ts',
    ),
    emailPathModule,
  ],
] as const;

if (process.argv.includes('--check')) {
  for (const [output, expected] of outputs) {
    if (readFileSync(output, 'utf8') !== expected) {
      throw new Error(`Generated logo differs: ${output}`);
    }
  }
} else {
  for (const [output, contents] of outputs) {
    writeFileSync(output, contents);
  }
}
