import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openCascade from 'replicad-opencascadejs';
import { setOC, type Drawing } from 'replicad';
import sharp from 'sharp';
import { tauBrandColor } from '../tau-brand.js';
import { createLetters, createSymbol, createTauWordmark } from './main.js';

setOC(openCascade);

const formatNumber = (value: number): string =>
  String(Number(value.toFixed(5)));
const formatPath = (path: string): string =>
  path.replaceAll(/-?\d+(?:\.\d+)?/g, (value) => formatNumber(Number(value)));
const pathData = (drawing: Drawing): string =>
  drawing
    .toSVGPaths()
    .flat()
    .map((path) => formatPath(path))
    .join(' ');

const wordmark = createTauWordmark();
const [[minX, minY], [maxX, maxY]] = wordmark.boundingBox.bounds;
// SVG y runs down: the drawing's top edge becomes the view box origin.
const viewBox = [minX, -maxY, maxX - minX, maxY - minY]
  .map((value) => formatNumber(Number(value.toFixed(2))))
  .join(' ');
const wordmarkPath = pathData(wordmark);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><path fill="${tauBrandColor}" fill-rule="evenodd" d="${wordmarkPath}"/></svg>\n`;
const png = await sharp(Buffer.from(svg), { density: 300 })
  .resize({ height: 512 })
  .png()
  .toBuffer();
const component = `// Generated by libs/tau-examples/src/kernels/replicad/tau-wordmark/generate-wordmark.ts. Do not edit.
export function TauWordmark(properties: React.SVGProps<SVGSVGElement>): React.JSX.Element {
  return (
    <svg xmlns='http://www.w3.org/2000/svg' viewBox='${viewBox}' {...properties}>
      <path
        fill='currentColor'
        fillRule='evenodd'
        d='${wordmarkPath}'
      />
    </svg>
  );
}
`;
const marketingModule = `// Generated by libs/tau-examples/src/kernels/replicad/tau-wordmark/generate-wordmark.ts. Do not edit.
/** The Tau wordmark: symbol and letters as separate even-odd paths, so each can take its own colour. */
export const wordmark = {
  viewBox: '${viewBox}',
  symbol:
    '${pathData(createSymbol())}',
  letters:
    '${pathData(createLetters())}',
};
`;

const directory = dirname(fileURLToPath(import.meta.url));
const workspaceRoot = join(directory, '../../../../../..');
const outputs = [
  [join(directory, 'wordmark.svg'), svg],
  [join(workspaceRoot, 'apps/ui/public/wordmark.svg'), svg],
  [join(workspaceRoot, 'apps/ui/public/wordmark.png'), png],
  [
    join(workspaceRoot, 'apps/ui/app/components/icons/tau-wordmark.tsx'),
    component,
  ],
  [join(workspaceRoot, 'apps/docs/app/components/tau-wordmark.tsx'), component],
  [join(workspaceRoot, 'apps/www/src/wordmark.mjs'), marketingModule],
] as const;

if (process.argv.includes('--check')) {
  for (const [output, expected] of outputs) {
    const expectedBytes =
      typeof expected === 'string' ? Buffer.from(expected) : expected;
    if (!readFileSync(output).equals(expectedBytes)) {
      throw new Error(`Generated wordmark differs: ${output}`);
    }
  }
} else {
  for (const [output, contents] of outputs) {
    writeFileSync(output, contents);
  }
}
