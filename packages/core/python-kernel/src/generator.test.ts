import { describe, expect, it } from 'vitest';

import {
  compactLock,
  evaluateMarker,
  markerEnvironment,
  parseRequirementsLock,
  readPylockWheels,
  renderPylock,
  selectWheel,
  variantFloor,
} from '#generator.js';
import type { IndexFile, TargetConfig } from '#generator.js';

const digest = (digit: string): string => digit.repeat(64);

const darwinArm64: TargetConfig = {
  key: 'darwin-arm64',
  os: 'darwin',
  arch: 'arm64',
  deploymentTarget: '12.0',
  interpreterFloor: '11.0',
  interpreter: { asset: 'cpython-darwin.tar.gz', sha256: digest('0'), byteLength: 1 },
};
const linuxArm64: TargetConfig = {
  key: 'linux-arm64-glibc',
  os: 'linux',
  arch: 'arm64',
  libc: 'glibc',
  glibcCeiling: '2.31',
  interpreterFloor: '2.17',
  interpreter: { asset: 'cpython-linux.tar.gz', sha256: digest('0'), byteLength: 1 },
};

const file = (filename: string, sha256: string, yanked = false): IndexFile => ({
  filename,
  url: `https://files.example/${filename}`,
  sha256,
  size: 10,
  yanked,
});

const lock = `numpy==2.3.0 ; python_version >= '3.11' \\
    --hash=sha256:${digest('a')} \\
    --hash=sha256:${digest('b')} \\
    --hash=sha256:${digest('c')}
lib3mf==2.5.0 ; platform_machine != 'aarch64' or sys_platform != 'linux' \\
    --hash=sha256:${digest('d')}
py-lib3mf==2.5.0 ; platform_machine == 'aarch64' and sys_platform == 'linux' \\
    --hash=sha256:${digest('e')}
`;

const index = new Map<string, IndexFile[]>([
  [
    'numpy==2.3.0',
    [
      file('numpy-2.3.0-cp313-cp313-macosx_14_0_arm64.whl', digest('a')),
      file('numpy-2.3.0-cp313-cp313-macosx_11_0_arm64.whl', digest('b')),
      file('numpy-2.3.0-cp313-cp313-manylinux_2_27_aarch64.manylinux_2_28_aarch64.whl', digest('c')),
      file('numpy-2.3.0.tar.gz', digest('f')),
    ],
  ],
  ['lib3mf==2.5.0', [file('lib3mf-2.5.0-py3-none-any.whl', digest('d'))]],
  ['py-lib3mf==2.5.0', [file('py_lib3mf-2.5.0-py3-none-manylinux_2_17_aarch64.whl', digest('e'))]],
]);

describe('the Python kernel lock compactor', () => {
  it('should evaluate PEP 508 markers against each target', () => {
    expect(evaluateMarker("python_version >= '3.11'", markerEnvironment(darwinArm64))).toBe(true);
    expect(evaluateMarker("python_version < '3.9'", markerEnvironment(darwinArm64))).toBe(false);
    expect(
      evaluateMarker("platform_machine == 'aarch64' and sys_platform == 'linux'", markerEnvironment(linuxArm64)),
    ).toBe(true);
    expect(
      evaluateMarker("platform_machine != 'aarch64' or sys_platform != 'linux'", markerEnvironment(linuxArm64)),
    ).toBe(false);
    expect(evaluateMarker("(sys_platform == 'win32') or (os_name == 'posix')", markerEnvironment(darwinArm64))).toBe(
      true,
    );
  });

  it('should keep each target only the pins its markers select, with the best wheel under its OS bound', () => {
    const pins = parseRequirementsLock(lock);

    const darwin = compactLock(pins, index, darwinArm64);
    expect(darwin.map(({ file: { filename }, floor }) => ({ filename, floor }))).toEqual([
      // The macOS 14 wheel needs more than the 12.0 deployment target allows.
      { filename: 'numpy-2.3.0-cp313-cp313-macosx_11_0_arm64.whl', floor: '11.0' },
      { filename: 'lib3mf-2.5.0-py3-none-any.whl', floor: undefined },
    ]);
    expect(variantFloor(darwinArm64, darwin)).toBe('11.0');

    const linux = compactLock(pins, index, linuxArm64);
    expect(linux.map(({ file: { filename }, floor }) => ({ filename, floor }))).toEqual([
      { filename: 'numpy-2.3.0-cp313-cp313-manylinux_2_27_aarch64.manylinux_2_28_aarch64.whl', floor: '2.27' },
      { filename: 'py_lib3mf-2.5.0-py3-none-manylinux_2_17_aarch64.whl', floor: '2.17' },
    ]);
    expect(variantFloor(linuxArm64, linux)).toBe('2.27');
  });

  it('should refuse a yanked pinned wheel and a pin with no wheel for the target', () => {
    const [pin] = parseRequirementsLock(lock);

    expect(() =>
      selectWheel(pin!, [file('numpy-2.3.0-cp313-cp313-macosx_11_0_arm64.whl', digest('b'), true)], darwinArm64),
    ).toThrow(/yanked/u);
    expect(() =>
      selectWheel(pin!, [file('numpy-2.3.0-cp313-cp313-macosx_14_0_arm64.whl', digest('a'))], darwinArm64),
    ).toThrow(/no pinned wheel for darwin-arm64/u);
  });

  it('should render a pylock its reader decodes back to the chosen wheels', () => {
    const wheels = compactLock(parseRequirementsLock(lock), index, linuxArm64);

    const text = renderPylock(linuxArm64, wheels, { packageName: '@taucad/example', project: 'example' });
    const decoded = readPylockWheels(text);

    expect(text).toMatch(/^# Generated by `pnpm nx run example:generate-tau-plugin` from requirements.lock/u);
    expect(text).toContain('created-by = "@taucad/example tau-plugin generator"');

    expect([...decoded.values()]).toEqual(
      wheels.map(({ file: chosen }) => ({ url: chosen.url, sha256: chosen.sha256, size: chosen.size })),
    );
  });
});
