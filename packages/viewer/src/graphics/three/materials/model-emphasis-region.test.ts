import type { BufferAttribute } from 'three';
import { expect, it } from 'vitest';
import { BoxGeometry, Mesh, OrthographicCamera, PerspectiveCamera, PlaneGeometry } from 'three';
import { createEmphasisCompositeRegion } from '#graphics/three/materials/model-emphasis-region.js';

it('bounds the composite in original clip coordinates with device-pixel filter padding', () => {
  const geometry = new PlaneGeometry(2, 2);
  const update = createEmphasisCompositeRegion(geometry);
  const source = new Mesh(new BoxGeometry(1, 1, 1));
  const camera = new OrthographicCamera(-2, 2, 2, -2, 0.1, 10);
  camera.position.z = 3;
  camera.updateMatrixWorld();
  const size = { width: 400, height: 400, pixelRatio: 2 };
  update([{ source }], camera, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.min.x).toBeCloseTo(-0.27, 6);
  expect(geometry.boundingBox!.max.y).toBeCloseTo(0.27, 6);
  const { version } = geometry.attributes['position'] as BufferAttribute;
  update([{ source }], camera, size);
  expect((geometry.attributes['position'] as BufferAttribute).version).toBe(version);
  source.position.x = 1;
  source.updateMatrixWorld();
  update([{ source }], camera, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.min.x).toBeCloseTo(0.23, 6);
  update([], camera, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.min.x).toBe(-1);
  expect(geometry.boundingBox!.max.x).toBe(1);
});

it('keeps full coverage for eye-plane crossings and deformation and bounds the union of separate parts', () => {
  const geometry = new PlaneGeometry(2, 2);
  const update = createEmphasisCompositeRegion(geometry);
  const source = new Mesh(new BoxGeometry(1, 1, 1));
  const camera = new PerspectiveCamera(45, 1, 0.1, 10);
  const size = { width: 5120, height: 2880, pixelRatio: 2 };
  update([{ source }], camera, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.min.x).toBe(-1);
  camera.position.z = 3;
  camera.updateMatrixWorld();
  const other = new Mesh(source.geometry);
  source.position.x = -2;
  other.position.x = 2;
  source.updateMatrixWorld();
  other.updateMatrixWorld();
  update([{ source }, { source: other }], camera, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.min.x).toBe(-1);
  expect(geometry.boundingBox!.max.x).toBe(1);
  expect(geometry.boundingBox!.max.y).toBeLessThan(1);
  source.geometry.morphAttributes.position = [source.geometry.attributes['position']!];
  update([{ source }], camera, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.max.y).toBe(1);
});

it('retains padding at fractional DPR and restores bounds after offscreen motion and camera switching', () => {
  const geometry = new PlaneGeometry(2, 2);
  const update = createEmphasisCompositeRegion(geometry);
  const source = new Mesh(new BoxGeometry(1, 1, 1));
  const camera = new OrthographicCamera(-2, 2, 2, -2, 0.1, 10);
  camera.position.z = 3;
  camera.updateMatrixWorld();
  const size = { width: 5120, height: 2880, pixelRatio: 1.5 };
  source.position.x = 20;
  source.updateMatrixWorld();
  update([{ source }], camera, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.min.x).toBe(1);
  expect(geometry.boundingBox!.max.x).toBe(1);
  source.position.x = 0.001;
  source.updateMatrixWorld();
  update([{ source }], camera, size);
  geometry.computeBoundingBox();
  expect(((-0.2495 - geometry.boundingBox!.min.x) * size.width) / 2).toBeGreaterThanOrEqual(3.99);
  expect(((geometry.boundingBox!.max.x - 0.2505) * size.width) / 2).toBeGreaterThanOrEqual(3.99);
  const perspective = new PerspectiveCamera(45, size.width / size.height, 0.1, 10);
  perspective.position.z = 3;
  perspective.updateMatrixWorld();
  update([{ source }], perspective, size);
  geometry.computeBoundingBox();
  expect(geometry.boundingBox!.min.x).toBeLessThan(-0.27);
  expect(geometry.boundingBox!.max.x).toBeGreaterThan(0.27);
  expect(geometry.boundingBox!.max.x).toBeLessThan(0.3);
});
